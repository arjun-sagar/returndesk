// Input validation and normalisation. Shared by the API route handlers and the browser forms, so it must stay
// pure (no Node, DB or Next imports). This file checks FORMAT only; business rules live in rules.js.

import {
  DEFAULT_ORDER,
  DEFAULT_PAGE_SIZE,
  DEFAULT_SORT,
  FIELD_LIMITS,
  MAX_PAGE_SIZE,
  QUANTITY_MAX,
  QUANTITY_MIN,
  REASONS,
  REFUND_MAX,
  RESOLUTIONS,
  SORT_FIELDS,
  SORT_ORDERS,
  STATUSES,
} from './constants.js';

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const PHONE_PATTERN = /^\+?[0-9][0-9 ()-]{5,19}$/;
const CODE_PATTERN = /^[A-Z0-9#._/-]{1,40}$/;
const AMOUNT_PATTERN = /^-?\d+(\.\d{1,2})?$/;
const REQUEST_ID_PATTERN = /^[1-9]\d{0,9}$/;
const MAX_REQUEST_ID = 2147483647;
const MAX_PAGE_NUMBER = 999999999;

const CREATE_FIELDS = ['customerName', 'customerEmail', 'customerPhone', 'orderNumber', 'itemSku', 'itemName', 'quantity', 'reason'];
const NOTE_FIELDS = ['author', 'body'];
const TRANSITION_FIELDS = ['status', 'resolution', 'refundAmount'];
const READ_ONLY_FIELDS = ['id', 'createdAt', 'updatedAt', 'removedAt'];

// ---------------------------------------------------------------- normalizers

// Trims the text and collapses runs of whitespace into single spaces. Non-strings pass through unchanged.
export function normalizeText(value) {
  return typeof value === 'string' ? value.trim().replace(/\s+/g, ' ') : value;
}

// Trims and uppercases a code such as an order number or SKU. Non-strings pass through unchanged.
export function normalizeCode(value) {
  return typeof value === 'string' ? value.trim().toUpperCase() : value;
}

// Trims and lowercases an email address. Non-strings pass through unchanged.
export function normalizeEmail(value) {
  return typeof value === 'string' ? value.trim().toLowerCase() : value;
}

// Trims a phone number. Non-strings pass through unchanged.
export function normalizePhone(value) {
  return typeof value === 'string' ? value.trim() : value;
}

// ---------------------------------------------------------------- helpers

// True for a non-null, non-array object (the only valid shape for a request body).
function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

// Counts characters the way Postgres char_length does (code points, not UTF-16 units).
function charLength(text) {
  return Array.from(text).length;
}

// Treats undefined, null and blank strings as "not provided".
function isBlank(value) {
  return value === undefined || value === null || (typeof value === 'string' && value.trim() === '');
}

// Adds an error for every body key that is not in `known`, using the specific message the API contract defines.
// `statusKeysRedirect` is true for create/update, where status-ish keys must go through the transitions endpoint.
function rejectUnknownFields(body, known, errors, statusKeysRedirect) {
  for (const key of Object.keys(body)) {
    if (known.includes(key)) continue;
    if (key === 'reference') {
      errors[key] = 'reference is generated by the system and cannot be set';
    } else if (statusKeysRedirect && TRANSITION_FIELDS.includes(key)) {
      errors[key] = 'use POST /api/requests/:id/transitions to change status';
    } else if (READ_ONLY_FIELDS.includes(key)) {
      errors[key] = `${key} is read-only`;
    } else {
      errors[key] = `${key} is not a recognised field`;
    }
  }
}

// Validates a required single-line text field; returns the normalized value or sets errors[key].
function requiredText(raw, key, label, max, errors, normalize = normalizeText) {
  if (typeof raw !== 'string') {
    errors[key] = raw === undefined || raw === null ? `${label} is required.` : `${label} must be text.`;
    return undefined;
  }
  const value = normalize(raw);
  if (value === '') {
    errors[key] = `${label} is required.`;
    return undefined;
  }
  if (charLength(value) > max) {
    errors[key] = `${label} must be at most ${max} characters.`;
    return undefined;
  }
  return value;
}

// Validates a required code (order number / SKU): normalized, no spaces, limited character set.
function requiredCode(raw, key, label, errors) {
  const value = requiredText(raw, key, label, FIELD_LIMITS.code, errors, normalizeCode);
  if (value === undefined) return undefined;
  if (!CODE_PATTERN.test(value)) {
    errors[key] = `${label} may only contain letters, numbers and # . _ / - (no spaces).`;
    return undefined;
  }
  return value;
}

// Validates an optional email: blank becomes null. Returns undefined (and sets errors[key]) when invalid.
function optionalEmail(raw, errors) {
  if (isBlank(raw)) return null;
  if (typeof raw !== 'string') {
    errors.customerEmail = 'Email must be text.';
    return undefined;
  }
  const value = normalizeEmail(raw);
  if (charLength(value) > FIELD_LIMITS.email || !EMAIL_PATTERN.test(value)) {
    errors.customerEmail = 'Enter a valid email address, for example name@example.com.';
    return undefined;
  }
  return value;
}

// Validates an optional phone: blank becomes null; needs 7+ digits and a plausible format.
function optionalPhone(raw, errors) {
  if (isBlank(raw)) return null;
  if (typeof raw !== 'string') {
    errors.customerPhone = 'Phone must be text.';
    return undefined;
  }
  const value = normalizePhone(raw);
  const digits = value.replace(/\D/g, '').length;
  if (value.length > FIELD_LIMITS.phone || !PHONE_PATTERN.test(value) || digits < 7) {
    errors.customerPhone = 'Enter a valid phone number with at least 7 digits, for example +91 98765 43210.';
    return undefined;
  }
  return value;
}

// Validates quantity: must be a JSON integer in range (numeric strings and decimals are rejected).
function requiredQuantity(raw, errors) {
  if (raw === undefined || raw === null) {
    errors.quantity = 'Quantity is required.';
    return undefined;
  }
  if (typeof raw !== 'number' || !Number.isInteger(raw) || raw < QUANTITY_MIN || raw > QUANTITY_MAX) {
    errors.quantity = `Quantity must be a whole number between ${QUANTITY_MIN} and ${QUANTITY_MAX}.`;
    return undefined;
  }
  return raw;
}

// Validates the return reason: must be exactly one of REASONS.
function requiredReason(raw, errors) {
  if (raw === undefined || raw === null || raw === '') {
    errors.reason = 'Reason is required.';
    return undefined;
  }
  if (typeof raw !== 'string' || !REASONS.includes(raw)) {
    errors.reason = `Reason must be one of: ${REASONS.join(', ')}.`;
    return undefined;
  }
  return raw;
}

// Per-field validators for the create/update field set; each returns the normalized value or undefined (error set).
const FIELD_VALIDATORS = {
  customerName: (raw, errors) => requiredText(raw, 'customerName', 'Customer name', FIELD_LIMITS.customerName, errors),
  customerEmail: optionalEmail,
  customerPhone: optionalPhone,
  orderNumber: (raw, errors) => requiredCode(raw, 'orderNumber', 'Order number', errors),
  itemSku: (raw, errors) => requiredCode(raw, 'itemSku', 'Item SKU', errors),
  itemName: (raw, errors) => requiredText(raw, 'itemName', 'Item name', FIELD_LIMITS.itemName, errors),
  quantity: requiredQuantity,
  reason: requiredReason,
};

const NOT_AN_OBJECT = { body: 'Request body must be a JSON object.' };

// ---------------------------------------------------------------- request validators

// Validates the body of POST /api/requests. All required fields must be present and at least one contact is needed.
export function validateCreateRequest(body) {
  if (!isPlainObject(body)) return { value: null, errors: { ...NOT_AN_OBJECT } };
  const errors = {};
  rejectUnknownFields(body, CREATE_FIELDS, errors, true);

  const value = {};
  for (const field of CREATE_FIELDS) {
    const result = FIELD_VALIDATORS[field](body[field], errors);
    if (result !== undefined) value[field] = result;
  }

  if (value.customerEmail === null && value.customerPhone === null) {
    errors.contact = 'Provide at least one contact method: an email address or a phone number.';
  }
  return { value, errors };
}

// Validates the body of PATCH /api/requests/:id. Partial: only supplied fields are checked and returned, and
// at least one known field is required. Email/phone may be cleared (null); the contact rule is re-checked by the service.
export function validateUpdateRequest(body) {
  if (!isPlainObject(body)) return { value: null, errors: { ...NOT_AN_OBJECT } };
  const errors = {};
  rejectUnknownFields(body, CREATE_FIELDS, errors, true);

  const value = {};
  let supplied = 0;
  for (const field of CREATE_FIELDS) {
    if (!Object.hasOwn(body, field)) continue;
    supplied += 1;
    const result = FIELD_VALIDATORS[field](body[field], errors);
    if (result !== undefined) value[field] = result;
  }

  if (supplied === 0 && Object.keys(errors).length === 0) {
    errors.body = `Provide at least one field to update: ${CREATE_FIELDS.join(', ')}.`;
  }
  return { value, errors };
}

// Parses refundAmount into a 2-decimal string. Returns undefined (and sets errors.refundAmount) when malformed.
// The sign is NOT judged here: "<= 0" is a business rule (422) enforced by rules.normalizeApproval.
function parseAmount(raw, errors) {
  let text;
  if (typeof raw === 'number') {
    text = Number.isFinite(raw) ? String(raw) : '';
  } else if (typeof raw === 'string') {
    text = raw.trim();
  } else {
    text = '';
  }
  if (!AMOUNT_PATTERN.test(text)) {
    errors.refundAmount = 'Refund amount must be a number with at most 2 decimal places, for example 1499.00.';
    return undefined;
  }
  const amount = Number(text);
  if (amount > REFUND_MAX) {
    errors.refundAmount = 'Refund amount must not exceed 1,000,000.';
    return undefined;
  }
  return amount.toFixed(2);
}

// Validates the body of POST /api/requests/:id/transitions: a known status, plus resolution/refundAmount only
// when approving. Returns { status, resolution, refundAmount } with missing optional values as null.
export function validateTransitionInput(body) {
  if (!isPlainObject(body)) return { value: null, errors: { ...NOT_AN_OBJECT } };
  const errors = {};
  rejectUnknownFields(body, TRANSITION_FIELDS, errors, false);

  const value = { status: null, resolution: null, refundAmount: null };

  if (isBlank(body.status)) {
    errors.status = 'Status is required.';
  } else if (typeof body.status !== 'string' || !STATUSES.includes(body.status)) {
    errors.status = `Status must be one of: ${STATUSES.join(', ')}.`;
  } else {
    value.status = body.status;
  }

  const approving = value.status === 'Approved';
  const knownStatus = value.status !== null;

  if (!isBlank(body.resolution)) {
    if (knownStatus && !approving) {
      errors.resolution = 'A resolution can only be set when approving a request.';
    } else if (typeof body.resolution !== 'string' || !RESOLUTIONS.includes(body.resolution)) {
      errors.resolution = `Resolution must be one of: ${RESOLUTIONS.join(', ')}.`;
    } else {
      value.resolution = body.resolution;
    }
  }

  if (!isBlank(body.refundAmount)) {
    if (knownStatus && !approving) {
      errors.refundAmount = 'A refund amount can only be set when approving a request.';
    } else {
      const amount = parseAmount(body.refundAmount, errors);
      if (amount !== undefined) value.refundAmount = amount;
    }
  }

  return { value, errors };
}

// Validates the body of POST /api/requests/:id/notes. The note body keeps internal newlines; only the ends are trimmed.
export function validateNoteInput(body) {
  if (!isPlainObject(body)) return { value: null, errors: { ...NOT_AN_OBJECT } };
  const errors = {};
  rejectUnknownFields(body, NOTE_FIELDS, errors, false);

  const value = {};
  const author = requiredText(body.author, 'author', 'Author', FIELD_LIMITS.author, errors);
  if (author !== undefined) value.author = author;

  const noteBody = requiredText(body.body, 'body', 'Note', FIELD_LIMITS.noteBody, errors, (text) => text.trim());
  if (noteBody !== undefined) value.body = noteBody;

  return { value, errors };
}

// ---------------------------------------------------------------- query / id helpers

// Reads one query param as a trimmed string; blank or missing becomes null.
function readParam(searchParams, name) {
  const raw = searchParams.get(name);
  if (raw === null || raw.trim() === '') return null;
  return raw.trim();
}

// Validates GET /api/requests query params and applies defaults. Unknown params are ignored.
// The returned sort/order are always members of the allowlists, so they are safe to map to SQL.
export function parseListQuery(searchParams) {
  const errors = {};
  const value = {
    q: null,
    status: null,
    reason: null,
    sort: DEFAULT_SORT,
    order: DEFAULT_ORDER,
    page: 1,
    pageSize: DEFAULT_PAGE_SIZE,
  };

  const q = readParam(searchParams, 'q');
  if (q !== null) {
    const normalized = normalizeText(q);
    if (charLength(normalized) > FIELD_LIMITS.search) {
      errors.q = `Search must be at most ${FIELD_LIMITS.search} characters.`;
    } else {
      value.q = normalized;
    }
  }

  const status = readParam(searchParams, 'status');
  if (status !== null) {
    if (STATUSES.includes(status)) value.status = status;
    else errors.status = `status must be one of: ${STATUSES.join(', ')}.`;
  }

  const reason = readParam(searchParams, 'reason');
  if (reason !== null) {
    if (REASONS.includes(reason)) value.reason = reason;
    else errors.reason = `reason must be one of: ${REASONS.join(', ')}.`;
  }

  const sort = readParam(searchParams, 'sort');
  if (sort !== null) {
    if (SORT_FIELDS.includes(sort)) value.sort = sort;
    else errors.sort = `sort must be one of: ${SORT_FIELDS.join(', ')}.`;
  }

  const order = readParam(searchParams, 'order');
  if (order !== null) {
    if (SORT_ORDERS.includes(order)) value.order = order;
    else errors.order = `order must be one of: ${SORT_ORDERS.join(', ')}.`;
  }

  const page = readParam(searchParams, 'page');
  if (page !== null) {
    if (/^\d+$/.test(page) && Number(page) >= 1 && Number(page) <= MAX_PAGE_NUMBER) value.page = Number(page);
    else errors.page = 'page must be a whole number of 1 or more.';
  }

  const pageSize = readParam(searchParams, 'pageSize');
  if (pageSize !== null) {
    if (/^\d+$/.test(pageSize) && Number(pageSize) >= 1 && Number(pageSize) <= MAX_PAGE_SIZE) value.pageSize = Number(pageSize);
    else errors.pageSize = `pageSize must be a whole number between 1 and ${MAX_PAGE_SIZE}.`;
  }

  return { value, errors };
}

// Parses the :id path segment into a positive 32-bit integer. Returns { value, error }; this prevents a
// Postgres integer-overflow 500 for ids such as 99999999999999999999.
export function parseRequestId(raw) {
  const text = typeof raw === 'string' || typeof raw === 'number' ? String(raw) : '';
  if (!REQUEST_ID_PATTERN.test(text) || Number(text) > MAX_REQUEST_ID) {
    return { value: null, error: 'id must be a positive whole number.' };
  }
  return { value: Number(text), error: null };
}

// Escapes LIKE/ILIKE wildcards (and the escape character itself) so user search text is matched literally.
export function escapeLike(q) {
  return String(q).replace(/[\\%_]/g, '\\$&');
}
